#!/usr/bin/env node
import path from "path";
import { parseCliArgs } from "../src/cli-args.mjs";
import { exportSql } from "../src/export.mjs";

const usage =
  "Usage: db-tools-export-policies [--env path] [--output path] [--bootstrap]";
const { env, output, help, bootstrap } = parseCliArgs({
  argv: process.argv.slice(2),
  defaults: { env: ".env.local", output: null, help: false, bootstrap: false },
  usage,
});

if (help) {
  console.log(usage);
  process.exit(0);
}

const defaultOutput = path.join("db", "policies.sql");

await exportSql({
  rpcName: "export_policies",
  envPath: env,
  outputPath: output ?? defaultOutput,
  headerLines: [
    "-- Policies exported from Supabase (public schema)",
    "-- Generated by db-tools (export-policies)",
  ],
  transformLines: (lines) => {
    const formattedLines = [];
    lines.forEach((line) => {
      formattedLines.push(line);
      if (/^create policy /i.test(line)) {
        formattedLines.push("");
      }
    });
    return formattedLines;
  },
  bootstrap,
});
