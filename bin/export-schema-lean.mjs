#!/usr/bin/env node
import path from "path";
import { parseCliArgs } from "../src/cli-args.mjs";
import { exportSql } from "../src/export.mjs";

const usage =
  "Usage: db-tools-export-schema [--env path] [--output path] [--bootstrap]";
const { env, output, help, bootstrap } = parseCliArgs({
  argv: process.argv.slice(2),
  defaults: { env: ".env.local", output: null, help: false, bootstrap: false },
  usage,
});

if (help) {
  console.log(usage);
  process.exit(0);
}

const defaultOutput = path.join("db", "schema.sql");

await exportSql({
  rpcName: "export_schema_lean",
  envPath: env,
  outputPath: output ?? defaultOutput,
  headerLines: [
    "-- Lean schema exported from Supabase (public schema)",
    "-- Tables, columns, constraints, indexes only",
    "-- Generated by db-tools (export-schema-lean)",
  ],
  bootstrap,
});
