#!/usr/bin/env node
import path from "path";
import { parseCliArgs } from "../src/cli-args.mjs";
import { exportSql } from "../src/export.mjs";

const usage = "Usage: db-tools-export-functions [--env path] [--output path]";
const { env, output, help } = parseCliArgs({
  argv: process.argv.slice(2),
  defaults: { env: ".env.local", output: null, help: false },
  usage,
});

if (help) {
  console.log(usage);
  process.exit(0);
}

const defaultOutput = path.join("db", "functions.sql");

await exportSql({
  rpcName: "export_functions",
  envPath: env,
  outputPath: output ?? defaultOutput,
  headerLines: [
    "-- Functions exported from Supabase (public schema)",
    "-- Generated by db-tools (export-functions)",
  ],
});
